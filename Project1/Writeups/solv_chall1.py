payload = [
    0x59, 0x55, 0x69, 0xDA, 0xB7,
    0x93, 0xFE, 0x76, 0x21, 0xAB,
    0xB0, 0xCA, 0x62, 0x7A, 0xF6,
    0x07, 0x93, 0xB0, 0x62, 0x81
]

state = 0x6D2B79F5
secret = bytearray()

for value in payload:
    state ^= (state << 13) & 0xFFFFFFFF
    state ^= state >> 17
    state ^= (state << 5) & 0xFFFFFFFF
    state &= 0xFFFFFFFF

    secret.append(value ^ (state & 0xFF))

print(secret.decode())


